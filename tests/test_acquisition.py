@pytest.mark.skipif(not os.path.exists(os.path.join(CACHE, "site_features.csv")), reason="no analysis cache")
def test_real_cache_flags_match_known_groups():
    sites, images = acq.load_site_tables(CACHE)
    f = acq.derive_flags(sites, images)
    assert len(f) == 31 and f.site.is_unique
    g = f.set_index("site")
    assert all(g.loc[s, "acquisition_group"] == "grey_pore" and g.loc[s, "grey_pore_source"] == "data+list" for s in GREY_PORE_SITES)
    assert all(g.loc[s, "acquisition_group"] == "low_contrast" for s in LOW_CONTRAST_SITES)
    assert all(g.loc[s, "acquisition_group"] == "cracked" for s in CRACKED_SITES)
    # the data rule alone reproduces the grey-pore list on Batches 1–3
    assert set(g.index[g.raised_black_level]) == set(GREY_PORE_SITES)
    assert f.acquisition_group.value_counts().to_dict() == {"ordinary": 22, "grey_pore": 4, "cracked": 3, "low_contrast": 2}


